import json
import os
from pathlib import Path
from openai import AsyncOpenAI, OpenAI

# Access API Key
api_key = os.getenv("SCHOOLAGENT_API_KEY")
if not api_key:
    raise ValueError("SCHOOLAGENT_API_KEY Environment variable not set")

# Parsing Profile Path
current_dir = Path(__file__).parent
config_path = current_dir.parent / "config" / "model.json"

# Read Profile
if not config_path.exists():
    raise FileNotFoundError(f"Profile not found: {config_path}")

with open(config_path, 'r', encoding='utf-8') as f:
    config = json.load(f)

# Initialize an odd client
teacher_client_async = AsyncOpenAI(
    api_key=api_key,
    base_url=config["teacher_api_url"]
)

student_client_async = AsyncOpenAI(
    api_key=api_key,
    base_url=config["student_api_url"]
)

textbook_client_async = AsyncOpenAI(
    api_key=api_key,
    base_url=config["textbook_api_url"]
)

evaluation_client_async = AsyncOpenAI(
    api_key=api_key,
    base_url=config["evaluation_api_url"]
)

# Initialize Sync client
teacher_client_sync = OpenAI(
    api_key=api_key,
    base_url=config["teacher_api_url"]
)

student_client_sync = OpenAI(
    api_key=api_key,
    base_url=config["student_api_url"]
)

textbook_client_sync = OpenAI(
    api_key=api_key,
    base_url=config["textbook_api_url"]
)

evaluation_client_sync = OpenAI(
    api_key=api_key,
    base_url=config["evaluation_api_url"]
)


async def call_LLM(role: str, messages: list, response_format: dict = None, temperature: float = 0.7):
    """
    A function of a large model interface to be moved from one step to the other, to the text content generated by the model

    Parameters:
    role: Role ('teacher', 'student', 'textbook' or 'evaluation')
    messages: Can not open message
    response_format: Response Format (Default as None)
    temperature: Generate Temperature (0-2 Between)

    Back:
    Text content generated by the model

    Unusual:
    ValueError: Role invalid
    """
    # Select client and model by character
    if role == "teacher":
        client = teacher_client_async
        model = config["teacher_model"]
    elif role == "student":
        client = student_client_async
        model = config["student_model"]
    elif role == "textbook":
        client = textbook_client_async
        model = config["textbook_model"]
    elif role == "evaluation":
        client = evaluation_client_async
        model = config["evaluation_model"]
    else:
        raise ValueError(f"Invalid character: {role},Must be 'teacher', 'student', 'textbook' or 'evaluation'")

    # Construct requested parameters
    params = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "stream": False
    }

    # Add Response Format (if available))
    if response_format:
        params["response_format"] = response_format

    try:
        completion = await client.chat.completions.create(**params)
        return completion.choices[0].message.content
    except Exception as e:
        print(f"[ERROR] Call a step LLM Failed: {e}")
        # Returns error information for subsequent processing
        return f"LLM error: {e}"


